// Merges every repo's BUILT.md into ALL_BUILT.md: newest day first, then repo. "### Internal" subsections are left out.
// Runs daily from .github/workflows/all-built.yml. Rules for BUILT.md: CLAUDE.md, "Feature backlog, built list and ideas".
// Local run: ALL_BUILT_LOCAL=<folder holding the repos> node scripts/all-built.mjs
import { readFileSync, writeFileSync } from 'node:fs'

export const REPOS = ['boardkit', 'calendarkit', 'footykit', 'gauntlet', 'linkkit', 'rotationkit', 'statmuse-builder']
const OWNER = 'AlexLCBranco'

async function fetchBuilt(repo) {
  if (process.env.ALL_BUILT_LOCAL) return readFileSync(`${process.env.ALL_BUILT_LOCAL}/${repo}/BUILT.md`, 'utf8')
  const headers = { Accept: 'application/vnd.github.raw+json' }
  if (process.env.GH_TOKEN) headers.Authorization = `Bearer ${process.env.GH_TOKEN}`
  const res = await fetch(`https://api.github.com/repos/${OWNER}/${repo}/contents/BUILT.md`, { headers })
  if (!res.ok) throw new Error(`HTTP ${res.status}`)
  return res.text()
}

export function parseBuilt(text) {
  const days = {}
  let date = null
  let internal = false
  for (const line of text.split('\n')) {
    const day = line.match(/^## (\d{4}-\d{2}-\d{2})/)
    if (day) { date = day[1]; internal = false; continue }
    if (/^###\s/.test(line)) { internal = /^###\s+Internal\b/i.test(line); continue }
    if (!date || internal) continue
    if (line.startsWith('- ')) (days[date] ??= []).push(line.slice(2).trim())
    else if (/^\s+\S/.test(line) && days[date]?.length) days[date][days[date].length - 1] += ` ${line.trim()}`
  }
  return days
}

export function merge(perRepo) {
  const byDay = {}
  for (const [repo, days] of Object.entries(perRepo))
    for (const [date, items] of Object.entries(days)) (byDay[date] ??= {})[repo] = items
  const out = []
  for (const date of Object.keys(byDay).sort().reverse()) {
    out.push(`## ${date}`, '')
    for (const repo of Object.keys(byDay[date]).sort()) {
      out.push(`**${repo}**`, ...byDay[date][repo].map((i) => `- ${i}`), '')
    }
  }
  return out
}

async function main() {
  const perRepo = {}
  const missing = []
  for (const repo of REPOS) {
    try { perRepo[repo] = parseBuilt(await fetchBuilt(repo)) } catch (e) { missing.push(`${repo} (${e.message})`) }
  }
  const head = [
    '# Built — all repos',
    '',
    'Generated by `scripts/all-built.mjs` from each repo\'s `BUILT.md` (daily, and on demand from the Actions tab). Do not',
    'edit by hand. Newest day first; "### Internal" housekeeping left out.',
    '',
  ]
  if (missing.length) head.push(`Not read this run: ${missing.join(', ')}.`, '')
  writeFileSync('ALL_BUILT.md', [...head, ...merge(perRepo)].join('\n').trimEnd() + '\n')
  console.log(`ALL_BUILT.md: ${Object.keys(perRepo).length} repos${missing.length ? `; missing ${missing.join(', ')}` : ''}`)
}

if (process.argv[1]?.endsWith('all-built.mjs')) await main()
